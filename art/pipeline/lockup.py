"""The Forged Force lockup: the anvil-shield emblem beside the stacked stencil wordmark "FORGED / FORCE", as real
vector paths (no live text, no font needed where it shows).

    python3 art/pipeline/lockup.py        # needs fontTools (pip install fonttools)

The letters are Big Shoulders Stencil Display Black (SIL OFL, the kit's display face, from @fontsource), turned
into outlines. FORCE is scaled to FORGED's width so the two lines make one block; the block leans up to the
right (a 5° skew). Layers, back to front: a hard offset shadow, a thick outline, the faces. It writes:

  apps/web/src/ui/lockupArt.ts                       the paths and the viewBox, for ui/Lockup.tsx and the landing
  apps/web/public/art/brand/forged-force-lockup.svg  colour (the kit's hex values: a file has no CSS tokens)
  apps/web/public/art/brand/forged-force-lockup-mono.svg  one colour (currentColor; black where nothing sets it)
"""
import math
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

REPO = Path(__file__).resolve().parents[2]
FONT = next((REPO / "node_modules/.pnpm").glob("@fontsource+big-shoulders-stencil-display@*/node_modules/@fontsource/big-shoulders-stencil-display/files/big-shoulders-stencil-display-latin-900-normal.woff"))

font = TTFont(FONT)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
UPM = font["head"].unitsPerEm
CAP = font["OS/2"].sCapHeight  # 1600 of 2000

CAP_H = 160.0  # line 1's cap height, in lockup units
TRACK = 6.0  # extra space between letters
LINE_GAP = 20.0
EMBLEM_GAP = 26.0
SKEW = math.tan(math.radians(5))  # the block leans up to the right
OUTLINE = 16.0  # the outline's full stroke width (half shows outside the letter)
SHADOW = (9.0, 11.0)  # the hard offset shadow


def word(text: str, x0: float, top: float, cap_h: float, width: float | None = None):
    """One line's outline as SVG path data, cap tops at `top`; stretched to `width` if given. Returns (d, width)."""
    s = cap_h / CAP
    natural = sum(font["hmtx"][cmap[ord(c)]][0] * s for c in text) + TRACK * (len(text) - 1)
    sx = (width / natural) if width else 1.0
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    x = x0
    for c in text:
        g = cmap[ord(c)]
        # font units (y up, baseline 0) → lockup units (y down, cap top at `top`)
        glyphs[g].draw(TransformPen(pen, (s * sx, 0, 0, -s, x, top + cap_h)))
        x += (font["hmtx"][g][0] * s + TRACK) * sx
    return pen.getCommands(), natural * sx


# the two lines: FORCE stretched to FORGED's width (and grown to keep its proportions)
line1_w = sum(font["hmtx"][cmap[ord(c)]][0] * CAP_H / CAP for c in "FORGED") + TRACK * 5
line2_nat = sum(font["hmtx"][cmap[ord(c)]][0] * CAP_H / CAP for c in "FORCE") + TRACK * 4
cap2 = CAP_H * line1_w / line2_nat
block_h = CAP_H + LINE_GAP + cap2

# the emblem (favicon.svg's 64×64 shield, x 5–59, y 2–63) as tall as the block, on the left
EMB_S = block_h / 61.0
emb_w = 54.0 * EMB_S
text_x = emb_w + EMBLEM_GAP
d1, _ = word("FORGED", text_x, 0.0, CAP_H)
d2, _ = word("FORCE", text_x, CAP_H + LINE_GAP, cap2, line1_w)
emb_t = f"matrix({EMB_S:.4f} 0 0 {EMB_S:.4f} {-5 * EMB_S:.2f} {-2 * EMB_S:.2f})"
EMB_STROKE = f"{OUTLINE / EMB_S:.3f}"  # the outline's width in the emblem's own (scaled) units

SHIELD = "M32 2l27 9v21c0 15.5-11 26.5-27 31C16 58.5 5 47.5 5 32V11z"
CUT = "M32 8.5l21 7V32c0 12.3-8.3 21.2-21 25.2C19.3 53.2 11 44.3 11 32V15.5z"
MARK = "M32 12.5l3 6.4 7 .8-5.2 4.8 1.4 6.9L32 28l-6.2 3.4 1.4-6.9-5.2-4.8 7-.8zM14 35h30c0 4.4-3.6 6.6-9 7v3.5h5.5V51h-21v-5.5H25V42c-4.6-.4-7.5-2.2-8.4-4.4L11 36.5zM46 35h5v4h-5z"
ANVIL_CUT = "M31 45.5h2V51h-2z"
# one colour: the ring (shield minus its cut) and the star and anvil (minus the anvil's notch), even-odd
MONO_EMBLEM = SHIELD + CUT + MARK + ANVIL_CUT

# the bounds: the unskewed block plus the outline and the shadow, then the skew (y -= x·tan)
w = text_x + line1_w
pad = OUTLINE / 2 + 2
x_min, x_max = -pad, w + pad + SHADOW[0]
y_min = -pad - x_max * SKEW
y_max = block_h + pad + SHADOW[1]
VIEW = f"{x_min:.1f} {y_min:.1f} {x_max - x_min:.1f} {y_max - y_min:.1f}"
SKEW_T = f"matrix(1 {-SKEW:.5f} 0 1 0 0)"
ratio = (x_max - x_min) / (y_max - y_min)

ts = f'''/**
 * The Forged Force lockup (generated by art/pipeline/lockup.py; don't edit by hand): the anvil-shield emblem
 * beside the stacked stencil "FORGED / FORCE" as outlines, leaning up to the right. ui/Lockup.tsx draws it in
 * the app; the landing (index.html) gets the same markup at build time (vite.config.ts); the share images and
 * posters use public/art/brand/forged-force-lockup*.svg.
 */
export const LOCKUP_VIEWBOX = '{VIEW}';
/** width ÷ height */
export const LOCKUP_RATIO = {ratio:.4f};
export const LOCKUP_SKEW = '{SKEW_T}';
export const LOCKUP_OUTLINE = {OUTLINE};
export const LOCKUP_SHADOW: readonly [number, number] = [{SHADOW[0]}, {SHADOW[1]}];
/** the emblem's place: favicon.svg's 64×64 paths under this transform */
export const LOCKUP_EMBLEM_T = '{emb_t}';
/** the outline's width inside the emblem's transform */
export const LOCKUP_EMBLEM_STROKE = {EMB_STROKE};
export const LOCKUP_EMBLEM = {{ shield: '{SHIELD}', cut: '{CUT}', mark: '{MARK}', notch: '{ANVIL_CUT}', mono: '{MONO_EMBLEM}' }} as const;
/** line 1 (FORGED) and line 2 (FORCE) */
export const LOCKUP_WORDS: readonly [string, string] = [
  '{d1}',
  '{d2}',
];

/**
 * The lockup as SVG markup with class hooks (`mf-lockup__*`, coloured by tokens in ui/lockup.css), for HTML that
 * isn't React (the landing, vite.config.ts). `label`: its accessible name; null hides it from screen readers
 * (the words are next to it in text). `mono`: one colour (currentColor), no outline or shadow.
 */
export function lockupMarkup(label: string | null, extraClass = '', mono = false): string {{
  const a11y = label === null ? 'aria-hidden="true"' : `role="img" aria-label="${{label}}"`;
  const cls = ['mf-lockup', mono ? 'mf-lockup--mono' : '', extraClass].filter(Boolean).join(' ');
  const words = LOCKUP_WORDS.map((d, i) => `<path class="mf-lockup__w${{i + 1}}" d="${{d}}"/>`).join('');
  const emblem = mono
    ? `<g transform="${{LOCKUP_EMBLEM_T}}"><path class="mf-lockup__shield" fill-rule="evenodd" d="${{LOCKUP_EMBLEM.mono}}"/></g>`
    : `<g transform="${{LOCKUP_EMBLEM_T}}"><path class="mf-lockup__shield" d="${{LOCKUP_EMBLEM.shield}}"/><path class="mf-lockup__cut" d="${{LOCKUP_EMBLEM.cut}}"/><path class="mf-lockup__mark" d="${{LOCKUP_EMBLEM.mark}}"/><path class="mf-lockup__cut" d="${{LOCKUP_EMBLEM.notch}}"/></g>`;
  const shape = `<g transform="${{LOCKUP_EMBLEM_T}}" stroke-width="${{LOCKUP_EMBLEM_STROKE}}"><path d="${{LOCKUP_EMBLEM.shield}}"/></g>${{LOCKUP_WORDS.map((d) => `<path d="${{d}}"/>`).join('')}}`;
  const back = mono
    ? ''
    : `<g class="mf-lockup__shadow" stroke-width="${{LOCKUP_OUTLINE}}" stroke-linejoin="round" transform="translate(${{LOCKUP_SHADOW[0]}} ${{LOCKUP_SHADOW[1]}})">${{shape}}</g>` +
      `<g class="mf-lockup__line" stroke-width="${{LOCKUP_OUTLINE}}" stroke-linejoin="round">${{shape}}</g>`;
  return `<svg class="${{cls}}" viewBox="${{LOCKUP_VIEWBOX}}" ${{a11y}} focusable="false"><g transform="${{LOCKUP_SKEW}}">${{back}}<g class="mf-lockup__face">${{emblem}}${{words}}</g></g></svg>`;
}}
'''
(REPO / "apps/web/src/ui/lockupArt.ts").write_text(ts)

# the files: colour (the kit's values) and one colour
INK, TEXT, VOLT = "#070806", "#f2eedf", "#d6ff3b"
CUT_C = "#0e100b"
shape = f'<g transform="{emb_t}" stroke-width="{EMB_STROKE}"><path d="{SHIELD}"/></g><path d="{d1}"/><path d="{d2}"/>'
colour = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEW}" width="{(x_max - x_min) * 2:.0f}" height="{(y_max - y_min) * 2:.0f}">
<title>Forged Force</title>
<g transform="{SKEW_T}">
<g fill="{INK}" stroke="{INK}" stroke-width="{OUTLINE}" stroke-linejoin="round" transform="translate({SHADOW[0]} {SHADOW[1]})">{shape}</g>
<g fill="{INK}" stroke="{INK}" stroke-width="{OUTLINE}" stroke-linejoin="round">{shape}</g>
<g transform="{emb_t}"><path fill="{VOLT}" d="{SHIELD}"/><path fill="{CUT_C}" d="{CUT}"/><path fill="{VOLT}" d="{MARK}"/><path fill="{CUT_C}" d="{ANVIL_CUT}"/></g>
<path fill="{TEXT}" d="{d1}"/>
<path fill="{VOLT}" d="{d2}"/>
</g>
</svg>
'''
mono = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="{VIEW}" width="{(x_max - x_min) * 2:.0f}" height="{(y_max - y_min) * 2:.0f}" fill="currentColor">
<title>Forged Force</title>
<g transform="{SKEW_T}">
<g transform="{emb_t}"><path fill-rule="evenodd" d="{MONO_EMBLEM}"/></g>
<path d="{d1}"/>
<path d="{d2}"/>
</g>
</svg>
'''
out = REPO / "apps/web/public/art/brand"
out.mkdir(parents=True, exist_ok=True)
(out / "forged-force-lockup.svg").write_text(colour)
(out / "forged-force-lockup-mono.svg").write_text(mono)
print(f"viewBox {VIEW} (ratio {ratio:.3f}); FORCE cap {cap2:.1f} vs FORGED {CAP_H}")
